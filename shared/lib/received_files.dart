import 'dart:io';

import 'transfer_utils.dart';

bool isTransferPartial(String name) =>
    RegExp(r'^\.nexodrop-[A-Za-z0-9_-]{32}\.part$').hasMatch(name);

Future<File> createTransferPartial(Directory directory) async {
  await directory.create(recursive: true);
  final file = File('${directory.path}/.nexodrop-${randomId()}.part');
  await file.create(exclusive: true);
  return file;
}

/// Reserve the final name exclusively before publishing a verified file.
/// Existing files, directories and symbolic links are never overwritten.
Future<File> publishReceivedFile(
  File source,
  Directory directory,
  String originalName,
) async {
  var name = safeName(originalName, windows: Platform.isWindows);
  if (isTransferPartial(name)) name = 'archivo-$name';
  final dot = name.lastIndexOf('.');
  final stem = dot > 0 ? name.substring(0, dot) : name;
  final extension = dot > 0 ? name.substring(dot) : '';
  for (var index = 0; ; index++) {
    final filename = index == 0 ? name : '$stem ($index)$extension';
    final target = File('${directory.path}/$filename');
    if (await FileSystemEntity.type(target.path, followLinks: false) !=
        FileSystemEntityType.notFound) {
      continue;
    }
    try {
      await target.create(exclusive: true);
    } on FileSystemException {
      if (await FileSystemEntity.type(target.path, followLinks: false) !=
          FileSystemEntityType.notFound) {
        continue;
      }
      rethrow;
    }
    try {
      return await source.rename(target.path);
    } catch (_) {
      // Only our empty reservation is removed; the source remains intact.
      if (await target.exists() && await target.length() == 0) {
        await target.delete();
      }
      rethrow;
    }
  }
}

/// Flatten only the folders generated by older NexoDrop releases.
/// Unrecognized directories and incomplete transfers are left untouched.
Future<void> migrateReceivedFiles(
  Directory destination, {
  Directory? legacy,
}) async {
  await destination.create(recursive: true);
  for (final root in [
    destination,
    if (legacy != null && legacy.path != destination.path) legacy,
  ]) {
    if (!await root.exists()) continue;
    final entries = await root.list(followLinks: false).toList();
    for (final entry in entries) {
      final name = entry.uri.pathSegments.where((s) => s.isNotEmpty).last;
      if (entry is Directory &&
          RegExp(r'^NexoDrop-[A-Za-z0-9_-]+$').hasMatch(name)) {
        for (final file in await entry.list(followLinks: false).toList()) {
          if (file is! File) continue;
          final filename = file.uri.pathSegments.last;
          if (filename == 'archivo.part' || isTransferPartial(filename)) {
            continue;
          }
          await publishReceivedFile(file, destination, filename);
        }
        if (await entry.list(followLinks: false).isEmpty) await entry.delete();
      } else if (root.path != destination.path &&
          entry is File &&
          !isTransferPartial(name) &&
          name != 'archivo.part') {
        await publishReceivedFile(entry, destination, name);
      }
    }
    if (root.path != destination.path &&
        await root.list(followLinks: false).isEmpty) {
      await root.delete();
    }
  }
}
